# Цей файл призначений для швидкого та зручного редагування товарів прямо на GitHub.
# Ви можете змінювати назви, описи або створювати дублікати будь-яких товарів.
#
# ------------------------------------------------------------------------------
# 1. PRODUCT_OVERRIDES — ЗМІНА НАЗВИ ТА ОПИСУ ІСНУЮЧОГО ТОВАРУ
# ------------------------------------------------------------------------------
# Ключем у словнику може бути будь-що з переліченого (регістр не має значення):
#   - Артикул товару: наприклад "sp10144" або "SP10144" (НАЙЗРУЧНІШЕ!)
#   - Повний ID товару: наприклад "2222_106619"
#   - ID без префіксу: наприклад "106619"
#
# Доступні поля:
#   - "name_ua" (або "name"): нова назва товару українською
#   - "description_ua" (або "description"): новий опис товару (HTML або текст)
#   (якщо поле не вказано — залишається оригінальне значення від постачальника)

PRODUCT_OVERRIDES = {
    # Товар: Магнітний павербанк 10000mAh MagSafe
    "sp10144": {
        "name_ua": "Магнітний павербанк 10000mAh MagSafe / Power Bank lightning / Повербанк магнітний бездротовий",
    },
}

# ------------------------------------------------------------------------------
# 2. PRODUCT_CLONES — СТВОРЕННЯ ДУБЛІВ (КЛОНІВ) ТОВАРІВ
# ------------------------------------------------------------------------------
# Створює додаткову копію товару в прайсі з власним унікальним ID, артикулом та назвою.
# Це дозволяє продавати той самий товар під різними назвами або модифікаціями (наприклад 10000mAh та 5000mAh).
#
# Обов'язкові поля:
#   - "source": артикул або ID оригінального товару (наприклад "sp10144")
#   - "id_suffix": суфікс до ID товару (наприклад "5000" -> у прайсі буде "2222_106619_5000")
#   - "article": артикул для дубля (наприклад "sp10144-5000")
#   - "name_ua": нова назва для дубля
#
# Опціональні поля:
#   - "description_ua": власний опис дубля (якщо не вказано — копіюється з оригіналу)
#   - "params": словник для заміни конкретних характеристик, наприклад:
#               {"Ємність акумулятора": "5000 мА*год"}

PRODUCT_CLONES = [
    {
        "source": "sp10144",
        "id_suffix": "5000",
        "article": "sp10144-5000",
        "name_ua": "Магнітний павербанк 5000mAh MagSafe / Power Bank lightning / Повербанк магнітний бездротовий",
        "params": {
            "Ємність акумулятора": "5000 мА*год",
        },
    },
]


# ==============================================================================
# СЛУЖБОВІ ФУНКЦІЇ ДЛЯ ПОШУКУ (НЕ ПОТРІБНО РЕДАГУВАТИ)
# ==============================================================================

def get_product_override(offer_id=None, raw_id=None, article=None):
    """
    Знаходить перевизначення назви/опису для товару.
    Перевіряє: артикул, повний offer_id, чистий raw_id (нечутливо до регістру).
    """
    if not PRODUCT_OVERRIDES:
        return None

    # Прямий збіг за точним ключем
    for key in (article, offer_id, raw_id):
        if key and key in PRODUCT_OVERRIDES:
            return PRODUCT_OVERRIDES[key]

    # Нечутливий до регістру та пробілів збіг
    candidates = set()
    for item in (article, offer_id, raw_id):
        if item:
            candidates.add(str(item).strip().upper())

    for k, val in PRODUCT_OVERRIDES.items():
        if k and str(k).strip().upper() in candidates:
            return val

    return None


def get_product_clones(offer_id=None, raw_id=None, article=None):
    """
    Повертає список конфігурацій дублів (клонів) для даного товару.
    """
    if not PRODUCT_CLONES:
        return []

    candidates = set()
    for item in (article, offer_id, raw_id):
        if item:
            candidates.add(str(item).strip().upper())

    matching_clones = []
    for clone_cfg in PRODUCT_CLONES:
        source_key = clone_cfg.get("source")
        if source_key and str(source_key).strip().upper() in candidates:
            matching_clones.append(clone_cfg)

    return matching_clones

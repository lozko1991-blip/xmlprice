    # --------------------------------------------------------------------------
    processed_offers = []
    seen_offer_ids   = set()

    for prefix, id_prefix, url, domain, root, currency_rates in feeds:
        count_ok          = 0
        count_low         = 0
        count_no          = 0
        count_price_err   = 0
        count_duplicate   = 0
        count_blacklist   = 0
        count_default_qty = 0
        
        # Статистика мов назв та описів (надійна, за наявністю тегів)
